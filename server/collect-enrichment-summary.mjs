export function legacyCollectStatus(status) {
  return {
    COLLECTED: "待处理",
    QUEUE_PENDING: "上架中",
    QUEUED: "上架中",
    VALIDATING: "上架中",
    SUBMITTING: "上架中",
    OZON_ACCEPTED: "上架中",
    CHECKING: "上架中",
    RECONCILING: "待核对",
    RETRY_PENDING: "上架中",
    SUCCEEDED: "已上架",
    PARTIAL_SUCCESS: "部分成功",
    FAILED: "失败",
    CANCEL_REQUESTED: "取消中",
    CANCELLED: "已取消",
  }[status] || status;
}

export function projectCollectItemEnrichment(enrichment,jobs=[],now=Date.now()){
  if(!enrichment||!jobs.length)return enrichment;
  const states = jobs.map(job => {
    const error = {
      code: job.last_error_json?.code || job.error_json?.code || '',
      message: job.last_error_json?.message || job.error_json?.message || '',
      diagnostic: job.last_error_json?.diagnostic || job.error_json?.diagnostic,
    };
    // This exact legacy message was generated by claim expiry, not an upstream result.
    const legacyRecovery = job.status !== 'SUCCESS' && ['ZONGZI_ENRICH_UPSTREAM_FAILED', 'OZON_ENRICH_UPSTREAM_FAILED'].includes(error.code)
      && error.message === '扩展执行超时，未收到补全结果' && !error.diagnostic;
    const waitingForExtension = legacyRecovery || (job.status === 'PROCESSING'
      && job.claim_expires_at && new Date(job.claim_expires_at).getTime() <= now);
    return {job, error, legacyRecovery, waitingForExtension};
  });
  const failures = states.filter(({job, error, legacyRecovery}) => job.status !== 'SUCCESS'
    && !legacyRecovery && (job.status === 'FAILED' || error.code || error.message))
    .map(({job, error}) => ({
      sku: job.sku, status: job.status, code: error.code, message: error.message,
      ...(error.diagnostic ? {diagnostic: Object.fromEntries(
        ['stage', 'upstreamCode', 'upstreamStatus', 'requestSent', 'extensionVersion']
          .filter(key => error.diagnostic[key] !== undefined)
          .map(key => [key, error.diagnostic[key]]),
      )} : {}),
    }));
  const projected = {...enrichment,
    completedSkus: jobs.filter(job => job.status === 'SUCCESS').length,
    totalSkus: jobs.length,
    failures,
    hasActiveJobs: states.some(({job, legacyRecovery}) => legacyRecovery
      || job.status === 'PENDING' || job.status === 'PROCESSING'),
  };
  const selected = states.find(({job, legacyRecovery}) => job.status === 'FAILED' && !legacyRecovery)
    || states.find(({job, waitingForExtension}) => job.status === 'PROCESSING' && !waitingForExtension)
    || states.find(({job, waitingForExtension}) => job.status !== 'SUCCESS' && waitingForExtension)
    || states.find(({job}) => job.status === 'PENDING');
  if (!selected) return projected;
  const {job, waitingForExtension} = selected;
  const failure = failures.find(failure => failure.sku === job.sku);
  return {...projected,
    status: job.status === 'FAILED' && !waitingForExtension ? 'NEEDS_ATTENTION' : 'PENDING_ENRICHMENT',
    missingSkus: jobs.filter(job => job.status !== 'SUCCESS').map(job => job.sku),
    executionState: waitingForExtension ? 'WAITING_FOR_EXTENSION' : job.status,
    attemptCount: Number(job.attempt_count) || 0,
    nextAttemptAt: job.next_attempt_at ? new Date(job.next_attempt_at).toISOString() : '',
    lastErrorCode: failure?.code || '',
    lastErrorMessage: failure?.message || '',
    lastErrorDiagnostic: failure?.diagnostic || null,
  };
}
